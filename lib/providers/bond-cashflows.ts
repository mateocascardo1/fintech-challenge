export function getBondCashflows(symbol: string): BondSpec | null {
  const upper = symbol.toUpperCase();
  const canonical = SYMBOL_ALIASES[upper] ?? upper;
  return BONDS[canonical] ?? null;
}

export function getUpcomingCashflows(symbol: string, count = 8): CashflowEvent[] {
  const spec = getBondCashflows(symbol);
  if (!spec) return [];
  const today = new Date().toISOString().slice(0, 10);
  return spec.cashflows.filter((cf) => cf.date >= today).slice(0, count);
}

export function getAllBondSymbols(): string[] {
  return Object.keys(BONDS);
}
